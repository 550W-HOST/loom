/// Serves one file out of the binary.
///
/// The rules are the ones a static client needs and no more: a file that is
/// embedded is served with its type and cache policy, a path without an
/// extension falls back to the entry document so history routing works, and a
/// missing *asset* is an honest 404 rather than the shell — a browser that gets
/// HTML where it asked for JavaScript reports a syntax error that hides the
/// real mistake.
fn embedded_response(path: &str, method: &Method) -> Response {
    if !is_read(method) {
        return not_found();
    }
    let Some(relative) = sanitize(path) else {
        return not_found();
    };
    let key = relative.to_string_lossy().replace('\\', "/");
    if let Some(bytes) = assets::get(&key) {
        return asset_response(
            Body::from(bytes),
            content_type_for(&relative),
            cache_for(path),
        );
    }
    if is_client_route(path) {
        return asset_response(Body::from(assets::INDEX_HTML), HTML, "no-cache");
    }
    not_found()
}

/// Maps a request path to a path under the UI root, rejecting traversal.
///
/// Nothing is served from outside `root`: `..`, absolute paths and prefixes are
/// refused rather than normalised, because a silently normalised path is a
/// sandbox escape waiting for the next refactor.
fn sanitize(path: &str) -> Option<PathBuf> {
    let trimmed = path.trim_start_matches('/');
    let mut out = PathBuf::new();
    for component in Path::new(trimmed).components() {
        match component {
            Component::Normal(part) => out.push(part),
            Component::CurDir => {}
            Component::RootDir | Component::ParentDir | Component::Prefix(_) => return None,
        }
    }
    // `/` and `/foo/` resolve to their `index.html`.
    if out.as_os_str().is_empty() || path.ends_with('/') {
        out.push("index.html");
    }
    Some(out)
}

/// Whether a path may fall back to the SPA shell. Files with an extension are
/// requested assets and must 404 honestly.
fn is_client_route(path: &str) -> bool {
    Path::new(path).extension().is_none()
}

fn is_read(method: &Method) -> bool {
    method == Method::GET || method == Method::HEAD
}

fn asset_response(body: Body, content_type: &'static str, cache: &'static str) -> Response {
    let mut response = Response::new(body);
    response
        .headers_mut()
        .insert(header::CONTENT_TYPE, HeaderValue::from_static(content_type));
    response
        .headers_mut()
        .insert(header::CACHE_CONTROL, HeaderValue::from_static(cache));
    response
}

fn content_type_for(path: &Path) -> &'static str {
    match path.extension().and_then(|ext| ext.to_str()).unwrap_or("") {
        "html" | "htm" => HTML,
        "js" | "mjs" => JS,
        "css" => CSS,
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "webp" => "image/webp",
        "avif" => "image/avif",
        "ico" => "image/x-icon",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "ttf" => "font/ttf",
        "otf" => "font/otf",
        "wasm" => "application/wasm",
        "txt" => "text/plain; charset=utf-8",
        "webmanifest" => "application/manifest+json",
        _ => "application/octet-stream",
    }
}

/// Content-hashed build assets are immutable; everything else is revalidated so
/// a redeploy is picked up without a hard refresh.
fn cache_for(path: &str) -> &'static str {
    if path.ends_with("index.html") || path.ends_with('/') || path == "/" {
        "no-cache"
    } else if path.contains("/assets/") {
        "public, max-age=31536000, immutable"
    } else {
        "public, max-age=3600"
    }
}

