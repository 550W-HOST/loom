fn not_found() -> Response {
    error_response(StatusCode::NOT_FOUND, "not found")
}

fn error_response(status: StatusCode, message: impl Into<String>) -> Response {
    (
        status,
        axum::Json(serde_json::json!({ "error": message.into() })),
    )
        .into_response()
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::body::Body;
    use axum::http::Request;
    use http_body_util::BodyExt;

    async fn body_text(response: Response) -> String {
        let bytes = response.into_body().collect().await.unwrap().to_bytes();
        String::from_utf8(bytes.to_vec()).unwrap()
    }

    #[tokio::test]
    async fn the_embedded_product_app_is_served() {
        // The bundle is compiled in, so a server always has a client to serve
        // and no configuration can change which one.
        let ui = Ui::from_config(None).unwrap();
        assert!(
            ui.describe().contains("embedded product app"),
            "{}",
            ui.describe()
        );

        let index = ui
            .clone()
            .handle(Request::builder().uri("/").body(Body::empty()).unwrap())
            .await;
        assert_eq!(index.status(), StatusCode::OK);
        assert_eq!(
            index.headers()[header::CONTENT_TYPE],
            HeaderValue::from_static(HTML)
        );
        let html = body_text(index).await;

        // The app's entry document references a content-hashed asset, and that
        // asset must come out of the same binary: an index.html without its
        // bundle answers 200 and paints nothing.
        let entry = html
            .split("src=\"")
            .nth(1)
            .and_then(|rest| rest.split('"').next())
            .expect("the app's index.html must reference a script");
        assert!(entry.starts_with("/assets/"), "{entry}");
        let asset = ui
            .clone()
            .handle(Request::builder().uri(entry).body(Body::empty()).unwrap())
            .await;
        assert_eq!(asset.status(), StatusCode::OK);
        assert_eq!(asset.headers()[header::CONTENT_TYPE], JS);
        assert!(asset.headers()[header::CACHE_CONTROL]
            .to_str()
            .unwrap()
            .contains("immutable"));
    }

    #[tokio::test]
    async fn client_routes_fall_back_to_the_shell_but_api_paths_do_not() {
        let ui = Ui::from_config(None).unwrap();

        let client = ui
            .clone()
            .handle(
                Request::builder()
                    .uri("/threads/thr_1")
                    .body(Body::empty())
                    .unwrap(),
            )
            .await;
        assert_eq!(client.status(), StatusCode::OK);
        assert_eq!(
            client.headers()[header::CONTENT_TYPE],
            HeaderValue::from_static(HTML)
        );
        assert!(body_text(client).await.contains("<html"));

        let api = ui
            .handle(
                Request::builder()
                    .uri("/api/v1/nope")
                    .body(Body::empty())
                    .unwrap(),
            )
            .await;
        assert_eq!(api.status(), StatusCode::NOT_FOUND);

        // A missing *asset* is a 404, not the shell: a browser handed HTML
        // where it asked for JavaScript reports a syntax error instead of the
        // real mistake.
        let asset = Ui::from_config(None)
            .unwrap()
            .handle(
                Request::builder()
                    .uri("/missing.js")
                    .body(Body::empty())
                    .unwrap(),
            )
            .await;
        assert_eq!(asset.status(), StatusCode::NOT_FOUND);
    }

    #[tokio::test]
    async fn traversal_out_of_the_bundle_is_refused() {
        // Even a path that could only escape into the *filesystem* is refused
        // before the lookup: the bundle is a lookup table, and a traversal is
        // an attempt to read something that is not in it.
        let response = Ui::from_config(None)
            .unwrap()
            .handle(
                Request::builder()
                    .uri("/../secret.txt")
                    .body(Body::empty())
                    .unwrap(),
            )
            .await;
        assert_eq!(response.status(), StatusCode::NOT_FOUND);
    }

    #[tokio::test]
    async fn a_relative_proxy_url_is_rejected() {
        assert!(Ui::from_config(Some("127.0.0.1:5173".into())).is_err());
    }

    #[tokio::test]
    async fn the_proxy_forwards_http_requests_to_the_dev_server() {
        use axum::routing::get;
        use std::net::SocketAddr;

        let upstream = axum::Router::new().route(
            "/hello.js",
            get(|| async { ([("content-type", JS)], "export const hello = 1;") }),
        );
        let listener = tokio::net::TcpListener::bind::<SocketAddr>("127.0.0.1:0".parse().unwrap())
            .await
            .unwrap();
        let addr = listener.local_addr().unwrap();
        tokio::spawn(async move {
            let _ = axum::serve(listener, upstream).await;
        });

        let ui = Ui::from_config(Some(format!("http://{addr}"))).unwrap();
        let response = ui
            .handle(
                Request::builder()
                    .uri("/hello.js")
                    .body(Body::empty())
                    .unwrap(),
            )
            .await;
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(body_text(response).await, "export const hello = 1;");
    }
}
